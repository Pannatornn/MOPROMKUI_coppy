def _negated_terms(terms: str) -> re.Pattern[str]:
    """Match a negated danger term that occurs inside a contextual rule."""
    return re.compile(
        rf"(?:ไม่มี|ไม่ได้|ยังไม่|ไม่เคย|ไม่ค่อย|ปฏิเสธ|ไม่)"
        rf"(?:มี|พบ|เป็น)?(?:อาการ)?\s*(?:{terms})"
    )


