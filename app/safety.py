def normalize(text: str) -> str:
    return re.sub(r"\s+", " ", text.strip().lower())


def _is_negated(text: str, start: int) -> bool:
    prefix = text[max(0, start - 32) : start].rstrip()
    return bool(_NEGATION.search(prefix))


def _first_non_negated_match(flag: RedFlag, text: str) -> re.Match[str] | None:
    """Return the first affirmed match, not merely the first textual occurrence."""
    for match in flag.pattern.finditer(text):
        internally_negated = bool(
            flag.internal_negation and flag.internal_negation.search(match.group())
        )
        if not _is_negated(text, match.start()) and not internally_negated:
            return match
    return None


def find_red_flags(text: str) -> list[dict[str, str]]:
    normalized = normalize(text)
    matches: list[dict[str, str]] = []
    for flag in RED_FLAGS:
        match = _first_non_negated_match(flag, normalized)
        if match:
            matches.append({"code": flag.code, "label": flag.label})
    return matches


def find_urgent_signals(text: str) -> list[dict[str, str]]:
    normalized = normalize(text)
    matches: list[dict[str, str]] = []
    for signal in URGENT_SIGNALS:
        match = _first_non_negated_match(signal, normalized)
        if match:
            matches.append({"code": signal.code, "label": signal.label})
    return matches


def ai_message_is_safe(text: str) -> bool:
    return not bool(_UNSAFE_AI.search(normalize(text)))


